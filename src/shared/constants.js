/** Скільки черепів дає пройдений рівень `level`. */
export function skullReward(level) {
  const n = Math.max(1, level | 0);
  return Math.round(HARDCORE.skullFirst * Math.pow(HARDCORE.skullGrowth, n - 1));
}

