/** Маска перків у число — саме її везе снапшот замість списку рядків. */
export function perkMask(ids) {
  let m = 0;
  PERKS.forEach((p, i) => { if (ids.has ? ids.has(p.id) : ids.includes(p.id)) m |= 1 << i; });
  return m;
}

export function hasPerk(mask, id) {
  const i = PERKS.findIndex((p) => p.id === id);
  return i >= 0 && (mask & (1 << i)) !== 0;
}

/**
 * Режим світу. `true` розуміється як хардкор — так старий виклик
 * `createWorld(true)` лишається чинним.
 */
export function modeOf(m) {
  if (m === true) return 'hardcore';
  if (!m) return 'normal';
  return m;
}

/** У скільки разів коротші рівні в цьому режимі. */
export function levelScaleFor(m) {
  const mode = modeOf(m);
  if (mode === 'hardcore') return HARDCORE.levelScale;
  if (mode === 'team') return TEAM.levelScale;
  return 1;
}
