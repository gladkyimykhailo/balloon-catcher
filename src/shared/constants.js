/**
 * Правила світу: у кожного режиму свої серця й свій розгін гравітації.
 * Приймає і рядок режиму, і старий булевий «хардкор» — див. `modeOf`.
 */
export function rulesFor(mode) {
  const m = modeOf(mode);
  const src = m === 'hardcore' ? HARDCORE : m === 'team' ? TEAM : null;
  if (!src) return RULES;
  return {
    lives: src.lives,
    respawnDelay: src.respawnDelay,
    gravityRamp: src.gravityRamp,
    maxGravity: src.maxGravity,
  };
}

